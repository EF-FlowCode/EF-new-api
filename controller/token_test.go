func TestValidateTokenGroupForUserUsesAdditionalCustomerTiers(t *testing.T) {
	originalRatios := ratio_setting.GroupRatio2JSONString()
	originalUsable := setting.UserUsableGroups2JSONString()
	t.Cleanup(func() {
		_ = ratio_setting.UpdateGroupRatioByJSONString(originalRatios)
		_ = setting.UpdateUserUsableGroupsByJSONString(originalUsable)
	})
	_ = ratio_setting.UpdateGroupRatioByJSONString(`{"base":1,"vip_token":1,"svip_token":1}`)
	_ = setting.UpdateUserUsableGroupsByJSONString(`{"base":"Base"}`)
	testconfig.Set(t, "group_ratio_setting", map[string]string{
		"group_special_usable_group": testconfig.JSON(t, map[string]map[string]string{
			"VIP":  {"+:vip_token": "VIP token group"},
			"SVIP": {"+:svip_token": "SVIP token group"},
		}),
	})

	db := setupTokenControllerTestDB(t)
	seedTokenUser(t, db, 1, "VIP", []string{"SVIP"})

	if err := validateTokenGroupForUser(1, "vip_token"); err != nil {
		t.Fatalf("expected primary tier token group to pass, got %v", err)
	}
	if err := validateTokenGroupForUser(1, "svip_token"); err != nil {
		t.Fatalf("expected additional tier token group to pass, got %v", err)
	}
	if err := db.Model(&model.User{Id: 1}).Update("additional_customer_tiers", model.NewGroupList(nil)).Error; err != nil {
		t.Fatalf("failed to remove additional customer tier: %v", err)
	}
	if err := validateTokenGroupForUser(1, "svip_token"); err == nil {
		t.Fatal("expected token group to be rejected after its customer tier is removed")
	}
}

func TestGetTokenKeyRequiresOwnershipAndReturnsFullKey(t *testing.T) {
	db := setupTokenControllerTestDB(t)
	token := seedToken(t, db, 1, "owned-token", "owner1234token5678")

	authorizedCtx, authorizedRecorder := newAuthenticatedContext(t, http.MethodPost, "/api/token/"+strconv.Itoa(token.Id)+"/key", nil, 1)
	authorizedCtx.Params = gin.Params{{Key: "id", Value: strconv.Itoa(token.Id)}}
	GetTokenKey(authorizedCtx)

	authorizedResponse := decodeAPIResponse(t, authorizedRecorder)
	if !authorizedResponse.Success {
		t.Fatalf("expected authorized key fetch to succeed, got message: %s", authorizedResponse.Message)
	}

	var keyData tokenKeyResponse
	if err := common.Unmarshal(authorizedResponse.Data, &keyData); err != nil {
		t.Fatalf("failed to decode token key response: %v", err)
	}
	if keyData.Key != token.GetFullKey() {
		t.Fatalf("expected full key %q, got %q", token.GetFullKey(), keyData.Key)
	}

	unauthorizedCtx, unauthorizedRecorder := newAuthenticatedContext(t, http.MethodPost, "/api/token/"+strconv.Itoa(token.Id)+"/key", nil, 2)
	unauthorizedCtx.Params = gin.Params{{Key: "id", Value: strconv.Itoa(token.Id)}}
	GetTokenKey(unauthorizedCtx)

	unauthorizedResponse := decodeAPIResponse(t, unauthorizedRecorder)
	if unauthorizedResponse.Success {
		t.Fatalf("expected unauthorized key fetch to fail")
	}
	if strings.Contains(unauthorizedRecorder.Body.String(), token.Key) {
		t.Fatalf("unauthorized key response leaked raw token key: %s", unauthorizedRecorder.Body.String())
	}
}
