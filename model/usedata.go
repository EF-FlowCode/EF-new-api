func GetQuotaDataGroupByUser(startTime int64, endTime int64) (quotaData []*QuotaData, err error) {
	var quotaDatas []*QuotaData
	err = DB.Table("quota_data").
		Select("username, created_at, sum(count) as count, sum(quota) as quota, sum(token_used) as token_used").
		Where("created_at >= ? and created_at <= ?", startTime, endTime).
		Group("username, created_at").
		Find(&quotaDatas).Error
	return quotaDatas, err
}

// GetUserModelUsageTopN 返回指定用户最近 since 时间戳以来调用次数 TopN 的模型聚合。
// 数据来源是每小时刷新的 quota_data，避免直接扫 logs 对 LOG_DB 造成压力。
func GetUserModelUsageTopN(userId int, since int64, topN int) ([]*QuotaData, error) {
	var rows []*QuotaData
	err := DB.Table("quota_data").
		Select("model_name, SUM(count) AS count, SUM(quota) AS quota, SUM(token_used) AS token_used").
		Where("user_id = ? AND created_at >= ?", userId, since).
		Group("model_name").
		Order("count DESC").
		Limit(topN).
		Scan(&rows).Error
	return rows, err
}

// GetModelRankingData returns per-model aggregates (count / quota / token_used)
// over [start, end). end<=0 means "no upper bound". Ordered by token_used DESC.
// Only model-level rollups — no user identity is selected, so it is safe to
// expose publicly (powers the public model leaderboard).
func GetModelRankingData(start int64, end int64) ([]*QuotaData, error) {
	var rows []*QuotaData
	q := DB.Table("quota_data").
		Select("model_name, SUM(count) AS count, SUM(quota) AS quota, SUM(token_used) AS token_used").
		Where("created_at >= ?", start)
	if end > 0 {
		q = q.Where("created_at < ?", end)
	}
	err := q.Group("model_name").Order("token_used DESC").Scan(&rows).Error
	return rows, err
}

// GetModelBucketUsage returns per-model token_used grouped into fixed-size time
// buckets over [start, end), for the leaderboard's stacked usage chart.
// bucketSeconds MUST be a fixed internal constant (3600 or 86400), never user
// input — it is inlined into the SQL as a literal. Bucketing is pure integer
// modulo arithmetic on the unix-second created_at column, which is portable
// across SQLite / MySQL / PostgreSQL (no DB-specific date functions). The
// bucket start is returned in CreatedAt.
func GetModelBucketUsage(start int64, end int64, bucketSeconds int) ([]*QuotaData, error) {
	if bucketSeconds <= 0 {
		bucketSeconds = 86400
	}
	bucketExpr := fmt.Sprintf("(created_at - created_at %% %d)", bucketSeconds)
	var rows []*QuotaData
	q := DB.Table("quota_data").
		Select(fmt.Sprintf("model_name, %s AS created_at, SUM(token_used) AS token_used", bucketExpr)).
		Where("created_at >= ?", start)
	if end > 0 {
		q = q.Where("created_at < ?", end)
	}
	err := q.Group(fmt.Sprintf("model_name, %s", bucketExpr)).Scan(&rows).Error
	return rows, err
}

